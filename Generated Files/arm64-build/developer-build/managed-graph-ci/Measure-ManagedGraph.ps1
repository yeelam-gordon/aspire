[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$RepositoryRoot,
    [Parameter(Mandatory)][string]$ResultsDirectory,
    [switch]$ValidateOnly
)

$ErrorActionPreference = 'Stop'
$RepositoryRoot = (Resolve-Path -LiteralPath $RepositoryRoot).Path
$source = '06efc928e31486923754398007f4f78003e04ee3'
$relativeEvidence = 'Generated Files/arm64-build/developer-build/managed-graph-ci/'
$scope = @('/p:SkipNativeBuild=true', '/p:SkipBundleDeps=true', '/p:SkipTestProjects=true', '/p:SkipPlaygroundProjects=true')
$entry = Join-Path $RepositoryRoot $(if ($IsWindows) { 'build.cmd' } else { 'build.sh' })
$dotnetRoot = Join-Path $RepositoryRoot '.dotnet'
$dotnet = Join-Path $dotnetRoot $(if ($IsWindows) { 'dotnet.exe' } else { 'dotnet' })
$env:MSBUILDTERMINALLOGGER = 'false'
$env:DOTNET_ROOT = $dotnetRoot
$env:DOTNET_ROOT_ARM64 = $dotnetRoot
$env:DOTNET_ROOT_X64 = Join-Path $dotnetRoot 'x64'
$env:DOTNET_MULTILEVEL_LOOKUP = '0'
if (Test-Path -LiteralPath $ResultsDirectory) { throw 'Refusing to overwrite an evidence directory.' }
New-Item -ItemType Directory -Path $ResultsDirectory -Force | Out-Null
$ResultsDirectory = (Resolve-Path -LiteralPath $ResultsDirectory).Path

function Assert-CleanSource
{
    $state = @(& git -C $RepositoryRoot status --porcelain --untracked-files=no)
    if ($LASTEXITCODE -ne 0 -or $state.Count) { throw "Tracked source must be pristine: $state" }
}

function Restore-GeneratedLocalization([string]$Directory)
{
    $changed = @(& git -C $RepositoryRoot diff --name-only)
    if ($LASTEXITCODE -ne 0) { throw 'Cannot inspect generated source changes.' }
    $allowed = @('cs', 'de', 'en', 'es', 'fr', 'it', 'ja', 'ko', 'pl', 'pt-BR', 'ru', 'tr', 'zh-Hans', 'zh-Hant') |
        ForEach-Object { "src/Aspire.ProjectTemplates/templates/aspire-empty/.template.config/localize/templatestrings.$_.json" }
    if (@($changed | Where-Object { $_ -notin $allowed }).Count) { throw "Unexpected source changes; refusing cleanup: $changed" }
    if ($changed.Count)
    {
        & git -C $RepositoryRoot diff -- @changed > (Join-Path $Directory 'generated-localization.patch')
        # Standard localization removes two stale choice placeholders. Only files
        # generated by this arm from its recorded pristine state may be restored.
        & git -C $RepositoryRoot restore -- @changed
        if ($LASTEXITCODE -ne 0) { throw 'Generated localization cleanup failed.' }
    }
    Assert-CleanSource
}

function Invoke-Setup([string]$Action, [string]$Directory)
{
    $timer = [Diagnostics.Stopwatch]::StartNew()
    & $entry $Action -configuration Debug @scope /nr:false *> (Join-Path $Directory "$($Action.TrimStart('-')).log")
    $code = $LASTEXITCODE
    $timer.Stop()
    $result = [ordered]@{
        command = "$entry $Action -configuration Debug " + ($scope -join ' ') + ' /nr:false'
        elapsedSeconds = $timer.Elapsed.TotalSeconds
        exitCode = $code
    }
    $result | ConvertTo-Json | Set-Content (Join-Path $Directory "$($Action.TrimStart('-')).json")
    if ($code -ne 0) { throw "Setup $Action failed ($code); not a timing sample." }
    return $result
}

Push-Location -LiteralPath $RepositoryRoot
try
{
    Assert-CleanSource
    $revision = (& git rev-parse HEAD).Trim()
    $changedFromSource = @(& git diff --name-only $source HEAD)
    if ($LASTEXITCODE -ne 0 -or @($changedFromSource | Where-Object {
        $_ -ne '.github/workflows/compare-arm64-developer-build.yml' -and -not $_.StartsWith($relativeEvidence)
    }).Count) { throw 'Instrumentation revision contains product changes.' }
    if ([Runtime.InteropServices.RuntimeInformation]::OSArchitecture.ToString() -ne 'Arm64' -or
        [Runtime.InteropServices.RuntimeInformation]::ProcessArchitecture.ToString() -ne 'Arm64') { throw 'Native ARM64 OS and PowerShell required.' }
    & $dotnet --info > (Join-Path $ResultsDirectory 'sdk-info.log')
    if ($LASTEXITCODE -ne 0) { throw 'Run repository bootstrap first.' }
    & $dotnet msbuild -version -nologo /nr:false > (Join-Path $ResultsDirectory 'msbuild-version.log')
    if ($LASTEXITCODE -ne 0) { throw 'Cannot identify MSBuild.' }
    if ((Get-Content (Join-Path $ResultsDirectory 'sdk-info.log') -Raw) -notmatch '11\.0\.100-rc\.2\.26504\.105' -or
        (Get-Content (Join-Path $ResultsDirectory 'sdk-info.log') -Raw) -notmatch 'Architecture:\s+arm64' -or
        (Get-Content (Join-Path $ResultsDirectory 'msbuild-version.log') -Raw) -notmatch '18\.12\.0') { throw 'Unexpected SDK/MSBuild version or architecture.' }
    if ($IsWindows)
    {
        $pe = foreach ($path in @($dotnet, (Join-Path $dotnetRoot 'shared/Microsoft.NETCore.App/10.0.8/hostpolicy.dll')))
        {
            $bytes = [IO.File]::ReadAllBytes($path)
            $machine = [BitConverter]::ToUInt16($bytes, [BitConverter]::ToInt32($bytes, 0x3c) + 4)
            if ($machine -ne 0xaa64) { throw "Not an ARM64 PE: $path" }
            [ordered]@{ path = $path; machine = '{0:X4}' -f $machine }
        }
        $pe | ConvertTo-Json | Set-Content (Join-Path $ResultsDirectory 'native-pe.json')
        Get-CimInstance Win32_Processor | Select-Object Name, NumberOfCores, NumberOfLogicalProcessors |
            ConvertTo-Json | Set-Content (Join-Path $ResultsDirectory 'hardware.json')
        Get-Volume -DriveLetter ([IO.Path]::GetPathRoot($RepositoryRoot).Substring(0, 1)) |
            Select-Object DriveLetter, FileSystem, DriveType, Size |
            ConvertTo-Json | Set-Content (Join-Path $ResultsDirectory 'volume.json')
    }
    elseif ($IsMacOS)
    {
        & sysctl machdep.cpu.brand_string hw.ncpu hw.physicalcpu hw.memsize > (Join-Path $ResultsDirectory 'hardware.log')
        if ($LASTEXITCODE -ne 0) { throw 'Cannot identify Mac hardware.' }
        & file $dotnet (Join-Path $dotnetRoot 'shared/Microsoft.NETCore.App/10.0.8/libhostpolicy.dylib') > (Join-Path $ResultsDirectory 'native-file.log')
        if ($LASTEXITCODE -ne 0 -or (Get-Content (Join-Path $ResultsDirectory 'native-file.log') -Raw) -notmatch 'arm64') { throw 'Cannot verify native Mac runtime.' }
        & df -h $RepositoryRoot > (Join-Path $ResultsDirectory 'volume.log')
    }
    @{
        source = $source; instrumentation = $revision; sourceChanges = $changedFromSource
        os = [Runtime.InteropServices.RuntimeInformation]::OSDescription
        osArchitecture = [Runtime.InteropServices.RuntimeInformation]::OSArchitecture.ToString()
        processArchitecture = [Runtime.InteropServices.RuntimeInformation]::ProcessArchitecture.ToString()
        logicalProcessorCount = [Environment]::ProcessorCount
        imageOS = $env:ImageOS; imageVersion = $env:ImageVersion
        runnerName = $env:RUNNER_NAME; runId = $env:GITHUB_RUN_ID
        order = @('normal-1', 'mt-1', 'mt-2', 'normal-2')
        scope = $scope; nodeReuse = $false
        cache = 'Fresh hosted checkout; bootstrap then clean and restore outside each build timing. NuGet, OS and compiler caches may warm; no cache-flush claim.'
    } | ConvertTo-Json -Depth 4 | Set-Content (Join-Path $ResultsDirectory 'provenance.json')
    $globalJson = Get-Content (Join-Path $RepositoryRoot 'global.json') -Raw | ConvertFrom-Json
    $toolset = Get-Content (Join-Path $RepositoryRoot "artifacts/toolset/$($globalJson.'msbuild-sdks'.'Microsoft.DotNet.Arcade.Sdk').txt") -TotalCount 1
    & $dotnet msbuild $toolset "/p:RepoRoot=$RepositoryRoot$([IO.Path]::DirectorySeparatorChar)" /p:Configuration=Debug @scope /nr:false -getItem:ProjectToBuild > (Join-Path $ResultsDirectory 'projects.json')
    if ($LASTEXITCODE -ne 0) { throw 'Cannot record evaluated project scope.' }
    $projects = (Get-Content (Join-Path $ResultsDirectory 'projects.json') -Raw | ConvertFrom-Json).Items.ProjectToBuild
    if (@($projects | Where-Object Identity -like '*.csproj').Count -ne 148 -or
        @($projects | Where-Object Identity -like '*OuterPreBuild.proj').Count -ne 1) { throw 'Unexpected selected project set.' }
    if ($ValidateOnly) { return }

    foreach ($arm in @('normal-1', 'mt-1', 'mt-2', 'normal-2'))
    {
        $output = Join-Path $ResultsDirectory $arm
        New-Item -ItemType Directory -Path $output | Out-Null
        Assert-CleanSource
        @{ commit = (& git rev-parse HEAD); trackedStatus = @(& git status --porcelain --untracked-files=no) } |
            ConvertTo-Json | Set-Content (Join-Path $output 'source-before.json')
        try
        {
            # OuterPreBuild validates project names and has no Rebuild target.
            $setup = @(Invoke-Setup '-clean' $output; Invoke-Setup '-restore' $output)
            $setup | ConvertTo-Json | Set-Content (Join-Path $output 'setup.json')
            Assert-CleanSource
            $binlog = Join-Path $RepositoryRoot "artifacts/log/Debug/p22-$arm.binlog"
            $arguments = @('-build', '-configuration', 'Debug') + $scope + @("/bl:$binlog", '/clp:PerformanceSummary', '/nr:false')
            if ($arm.StartsWith('mt-')) { $arguments += '/mt', '/m' }
            $started = [DateTimeOffset]::UtcNow
            $timer = [Diagnostics.Stopwatch]::StartNew()
            & $entry @arguments *> (Join-Path $output 'build.log')
            $code = $LASTEXITCODE
            $timer.Stop()
            @{
                arm = $arm; startedUtc = $started.ToString('O'); elapsedSeconds = $timer.Elapsed.TotalSeconds
                exitCode = $code; source = $source; instrumentation = $revision
                command = "$entry " + ($arguments -join ' '); setupIncluded = $false; msbuildNodeReuse = $false
            } | ConvertTo-Json | Set-Content (Join-Path $output 'result.json')
            if (Test-Path -LiteralPath $binlog) { Copy-Item $binlog (Join-Path $output 'build.binlog') }
            if ($code -ne 0) { throw "$arm failed ($code); not a timing sample." }
            $binRoot = Join-Path $RepositoryRoot 'artifacts/bin'
            $inventory = @(Get-ChildItem -LiteralPath $binRoot -Recurse -Filter 'Aspire*.dll' -File | Sort-Object FullName | ForEach-Object {
                $relative = [IO.Path]::GetRelativePath($binRoot, $_.FullName)
                $destination = Join-Path (Join-Path $output 'dlls') $relative
                New-Item -ItemType Directory -Path (Split-Path $destination) -Force | Out-Null
                Copy-Item -LiteralPath $_.FullName -Destination $destination
                [ordered]@{ path = $relative; bytes = $_.Length }
            })
            if (-not $inventory.Count) { throw 'No selected product DLLs produced.' }
            $inventory | ConvertTo-Json | Set-Content (Join-Path $output 'dll-inventory.json')
        }
        finally { Restore-GeneratedLocalization $output }
    }
    & (Join-Path $PSScriptRoot 'Analyze-ManagedGraph.ps1') -ResultsDirectory $ResultsDirectory
}
finally { Pop-Location }
